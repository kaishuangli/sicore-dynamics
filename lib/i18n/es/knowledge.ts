export function getKnowledgeCategoryFromHash(hash: string): KnowledgeCategoryId | null {
  const id = hash.replace(/^#/, "");
  return knowledgeCategories.some((category) => category.id === id)
    ? (id as KnowledgeCategoryId)
    : null;
}

