import { knowledgeCategories as knowledgeCategoriesEn } from "@/lib/knowledge";

type TopicInput = {
  title: string;
  summary?: string;
};

type CategoryInput = {
  id: string;
  index: string;
  title: string;
  titleZh: string;
  shortLabel: string;
  description: string;
  icon: string;
  accent: string;
  featured?: boolean;
  topics: TopicInput[];
};

function makeArticle(topic: TopicInput, slug: string) {
  return {
    title: topic.title,
    slug,
    summary:
      topic.summary ??
      `关于“${topic.title}”的工程参考，涵盖无线供电系统的设计、集成与部署。`,
    readTime: "6 分钟",
  };
}

function makeCategory(input: CategoryInput) {
  const enCategory = knowledgeCategoriesEn.find((category) => category.id === input.id);

  return {
    id: input.id,
    index: input.index,
    title: input.title,
    titleZh: input.titleZh,
    shortLabel: input.shortLabel,
    description: input.description,
    icon: input.icon,
    accent: input.accent,
    featured: input.featured ?? false,
    articles: input.topics.map((topic, index) =>
      makeArticle(topic, enCategory?.articles[index]?.slug ?? `topic-${index + 1}`),
    ),
  };
}

